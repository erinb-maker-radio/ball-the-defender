// Simple Supabase Leaderboard - Minimal API calls, focused functionality
// Loads leaderboard on game start and mode changes only

(function() {
    console.log('🎮 Simple Supabase Leaderboard Loading...');
    
    // Supabase configuration
    const SUPABASE_CONFIG = {
        url: 'https://bxhcbyypjfzpuxhftppv.supabase.co',
        anonKey: 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImJ4aGNieXlwamZ6cHV4aGZ0cHB2Iiwicm9sZSI6ImFub24iLCJpYXQiOjE3NTU4OTM4MTIsImV4cCI6MjA3MTQ2OTgxMn0.cOakT3KAfQiegW9YuAoS6pXXeo9u5C-xpriWVqLPpGs',
        tableName: 'ball_defender'
    };
    
    // Simple leaderboard cache - only what we need
    let currentLeaderboard = [];
    let currentMode = 'original';
    let lastModeChange = 0;
    
    // Enhanced mode detection function
    function detectGameMode(explicitMode = null) {
        console.log('🔍 Detecting game mode...');
        
        // Debug all available mode sources
        const sources = {
            explicit: explicitMode,
            currentGameMode: window.currentGameMode?.id,
            selectedGameMode: window.selectedGameMode,
            localStorage: localStorage.getItem('ballDefender_selectedMode'),
            fallback: 'original'
        };
        
        console.log('📊 Mode detection sources:', sources);
        
        // Priority order: explicit parameter -> currentGameMode -> selectedGameMode -> localStorage -> default
        let detectedMode;
        if (explicitMode) {
            detectedMode = explicitMode;
            console.log(`✅ Using explicit mode parameter: ${detectedMode}`);
        } else if (window.currentGameMode?.id) {
            detectedMode = window.currentGameMode.id;
            console.log(`✅ Using window.currentGameMode.id: ${detectedMode}`);
        } else if (window.selectedGameMode) {
            detectedMode = window.selectedGameMode;
            console.log(`✅ Using window.selectedGameMode: ${detectedMode}`);
        } else {
            const stored = localStorage.getItem('ballDefender_selectedMode');
            detectedMode = stored || 'original';
            console.log(`✅ Using localStorage/default: ${detectedMode}`);
        }
        
        // Validate the detected mode
        const validModes = ['original', 'iceFrost', 'ballGoBoom'];
        if (!validModes.includes(detectedMode)) {
            console.warn(`⚠️ Invalid mode detected: ${detectedMode}, falling back to 'original'`);
            detectedMode = 'original';
        }
        
        console.log(`🎮 Final detected mode: ${detectedMode}`);
        return detectedMode;
    }
    
    // Load leaderboard from Supabase
    async function loadLeaderboard(gameMode = 'original') {
        try {
            console.log(`📊 Loading leaderboard for ${gameMode}...`);
            
            // Build API URL with proper filtering and sorting - TOP 13 SCORES
            let url = `${SUPABASE_CONFIG.url}/rest/v1/${SUPABASE_CONFIG.tableName}`;
            url += `?Mode=eq.${gameMode}`;  // Filter by game mode (correct field name: Mode)
            url += `&order=Score.desc`;  // Sort by score descending (correct field name: Score)
            url += `&limit=13`;             // TOP 13 SCORES
            
            // Auto-authenticate for reading scores
            if (!window.SecureHighScoreAuth) {
                console.error('❌ SecureHighScoreAuth not available');
                return [];
            }
            
            const token = await window.SecureHighScoreAuth.authenticate();
            
            const response = await fetch(url, {
                headers: {
                    'apikey': SUPABASE_CONFIG.anonKey,
                    'Authorization': `Bearer ${token}` // Use authenticated token
                }
            });
            
            if (response.ok) {
                const scores = await response.json();
                
                // Convert to game's expected format (using correct field names)
                const formattedScores = scores.map((score, index) => ({
                    name: score.Player,  // Correct field name: Player
                    score: score.Score,  // Correct field name: Score
                    date: score.Date || new Date().toISOString()  // Correct field name: Date
                    // Note: rank is generated by display function, not stored
                }));
                
                console.log(`✅ Loaded ${formattedScores.length} scores for ${gameMode}`);
                console.log('📊 Sample formatted score:', formattedScores[0]);
                return formattedScores;
                
            } else {
                console.error(`❌ Failed to load leaderboard: ${response.status}`);
                return [];
            }
            
        } catch (error) {
            console.error('❌ Error loading leaderboard:', error);
            return [];
        }
    }
    
    // Add new score to Supabase
    async function addScore(playerName, playerScore, gameMode = 'original') {
        try {
            console.log(`🏆 Adding score: ${playerName} - ${playerScore} (${gameMode})`);
            
            // Validate input
            if (!playerName || !playerScore || playerScore < 0) {
                console.warn('❌ Invalid score data');
                return false;
            }
            
            // Use secure authentication for high score submission
            if (!window.SecureHighScoreAuth) {
                console.error('❌ SecureHighScoreAuth not available');
                showScoreNotification('❌ Authentication system not available', 0, 'error');
                return false;
            }

            await window.SecureHighScoreAuth.submitHighScore(playerName, playerScore, gameMode);
            
            console.log('✅ Score saved to Supabase with authentication!');
            
            // Show success notification
            showScoreNotification(playerName, playerScore);
            
            // Reload leaderboard for this mode only
            await refreshLeaderboardForMode(gameMode);
            
            return true;
            
        } catch (error) {
            console.error('❌ Error saving score:', error);
            showScoreNotification('❌ Failed to save high score', 0, 'error');
            return false;
        }
    }
    
    // Refresh leaderboard for specific mode
    async function refreshLeaderboardForMode(gameMode) {
        console.log(`🔄 Refreshing leaderboard for ${gameMode} (current: ${currentMode})`);
        
        // Always refresh if it's the current mode OR force switch to new mode
        if (gameMode === currentMode || gameMode) {
            // Force clear cache
            currentLeaderboard = [];
            currentMode = gameMode;
            
            console.log(`🧹 Force cleared cache for ${gameMode}`);
            
            // Load fresh data
            currentLeaderboard = await loadLeaderboard(gameMode);
            console.log(`✅ Reloaded ${currentLeaderboard.length} scores for ${gameMode}`);
            
            // Update game display if function exists
            if (window.updateLeaderboardDisplay) {
                console.log(`🔄 Updating display...`);
                window.updateLeaderboardDisplay();
            } else {
                console.warn(`⚠️ updateLeaderboardDisplay not available`);
            }
        }
    }
    
    // Show score notification
    function showScoreNotification(name, score) {
        const notification = document.createElement('div');
        notification.style.cssText = `
            position: fixed;
            top: 50%;
            left: 50%;
            transform: translate(-50%, -50%);
            background: linear-gradient(135deg, #4CAF50 0%, #45a049 100%);
            color: white;
            padding: 25px 35px;
            border-radius: 15px;
            font-family: 'Courier New', monospace;
            font-size: 18px;
            box-shadow: 0 10px 40px rgba(0,0,0,0.3);
            z-index: 10000;
            text-align: center;
        `;
        
        notification.innerHTML = `
            <div style="font-size: 24px; margin-bottom: 10px;">☁️ SCORE SAVED!</div>
            <div style="font-size: 20px; color: #64ffda; margin-bottom: 10px;">${name} - ${score.toLocaleString()}</div>
            <div style="font-size: 14px; opacity: 0.9;">
                Added to global leaderboard!
            </div>
        `;
        
        document.body.appendChild(notification);
        
        setTimeout(() => {
            notification.style.opacity = '0';
            notification.style.transition = 'opacity 0.5s';
            setTimeout(() => {
                if (notification.parentNode) {
                    document.body.removeChild(notification);
                }
            }, 500);
        }, 3000);
    }
    
    // Override game functions with simple implementations
    function overrideGameFunctions() {
        console.log('🔧 Setting up game function overrides...');
        
        // Override addToLeaderboard - store original first to avoid recursion
        const originalAddToLeaderboard = window.addToLeaderboard;
        window.addToLeaderboard = async function(playerName, playerScore, gameMode = null) {
            const mode = detectGameMode(gameMode);
            console.log(`🏆 Supabase addToLeaderboard called: ${playerName} - ${playerScore} (${mode})`);
            return await addScore(playerName, playerScore, mode);
        };
        
        // Also provide direct access to Supabase system
        window.addToSupabaseLeaderboard = async function(playerName, playerScore, gameMode = null) {
            const mode = detectGameMode(gameMode);
            console.log(`🏆 Direct Supabase call: ${playerName} - ${playerScore} (${mode})`);
            return await addScore(playerName, playerScore, mode);
        };
        
        // Override getLeaderboard - simple synchronous return
        window.getLeaderboard = function(gameMode = null) {
            const mode = detectGameMode(gameMode);
            
            console.log(`🎮 getLeaderboard: FINAL MODE = ${mode} (was ${currentMode})`);
            console.log(`🎮 Current leaderboard has ${currentLeaderboard.length} entries`);
            
            // If mode changed, load new leaderboard
            if (mode !== currentMode) {
                console.log(`🔄 Mode changed from ${currentMode} to ${mode}`);
                currentMode = mode;
                lastModeChange = Date.now();
                
                // Clear current leaderboard to avoid showing stale data
                currentLeaderboard = [];
                console.log(`🧹 Cleared leaderboard cache for mode switch`);
                
                // Load leaderboard asynchronously
                loadLeaderboard(mode).then(scores => {
                    currentLeaderboard = scores;
                    console.log(`✅ Loaded ${scores.length} scores for ${mode} - updating display`);
                    // Update display after loading
                    if (window.updateLeaderboardDisplay) {
                        window.updateLeaderboardDisplay();
                    }
                }).catch(error => {
                    console.error(`❌ Failed to load ${mode} leaderboard:`, error);
                    currentLeaderboard = []; // Keep empty on error
                });
            }
            
            // Return current leaderboard (may be empty if still loading)
            // For high score detection: if leaderboard is empty/loading, any reasonable score should be considered high
            if (currentLeaderboard.length === 0) {
                console.log(`⚠️ getLeaderboard returning empty array - leaderboard may still be loading`);
            }
            
            return currentLeaderboard;
        };
        
        // Add refresh function for manual updates
        window.refreshLeaderboard = async function() {
            console.log('🔄 Manual leaderboard refresh...');
            currentLeaderboard = await loadLeaderboard(currentMode);
            if (window.updateLeaderboardDisplay) {
                window.updateLeaderboardDisplay();
            }
        };
        
        // Add manual mode switching function for testing
        window.forceLeaderboardMode = async function(mode) {
            console.log(`🔧 FORCING leaderboard mode to: ${mode}`);
            currentMode = mode;
            currentLeaderboard = [];
            currentLeaderboard = await loadLeaderboard(mode);
            console.log(`✅ Forced mode switch: loaded ${currentLeaderboard.length} scores for ${mode}`);
            if (window.updateLeaderboardDisplay) {
                window.updateLeaderboardDisplay();
            }
        };
        
        // Add manual refresh function
        window.forceRefreshLeaderboard = async function() {
            console.log(`🔧 FORCE REFRESHING current leaderboard (${currentMode})`);
            const oldCount = currentLeaderboard.length;
            currentLeaderboard = [];
            currentLeaderboard = await loadLeaderboard(currentMode);
            console.log(`✅ Refreshed: ${oldCount} -> ${currentLeaderboard.length} scores for ${currentMode}`);
            
            if (window.updateLeaderboardDisplay) {
                window.updateLeaderboardDisplay();
                console.log(`🔄 Display updated`);
            }
            
            return currentLeaderboard;
        };
        
        console.log('✅ Game functions overridden');
    }
    
    // Initialize system
    async function initialize() {
        console.log('🚀 Initializing Simple Supabase Leaderboard...');
        
        // Wait for everything to be fully loaded
        function waitForGameReady() {
            // Wait for DOM, window load, and game scripts
            if (document.readyState !== 'complete' || !window.gameCore) {
                setTimeout(waitForGameReady, 500);
                return;
            }
            
            // Additional delay to ensure all game systems are ready
            setTimeout(async () => {
                console.log('🎮 Game ready, setting up leaderboard...');
                
                // Override game functions
                overrideGameFunctions();
                
                // Detect initial mode
                const initialMode = window.currentGameMode?.id || 
                                  window.selectedGameMode || 
                                  localStorage.getItem('ballDefender_selectedMode') ||
                                  'original';
                
                if (initialMode !== currentMode) {
                    console.log(`🔄 Initial mode detection: switching from ${currentMode} to ${initialMode}`);
                    currentMode = initialMode;
                }
                
                // Load initial leaderboard
                console.log(`📊 Loading initial leaderboard for ${currentMode}...`);
                currentLeaderboard = await loadLeaderboard(currentMode);
                
                // Update display only if it exists and is safe to call
                setTimeout(() => {
                    if (window.updateLeaderboardDisplay && typeof window.updateLeaderboardDisplay === 'function') {
                        try {
                            window.updateLeaderboardDisplay();
                        } catch (e) {
                            console.warn('⚠️ Could not update leaderboard display:', e);
                        }
                    }
                }, 100);
                
                console.log('✅ Simple Supabase Leaderboard Ready!');
                console.log(`📊 Loaded ${currentLeaderboard.length} scores for ${currentMode} mode`);
                
            }, 1000);
        }
        
        waitForGameReady();
    }
    
    // Expose utilities for debugging and testing
    window.SupabaseLeaderboard = {
        getCurrentScores: () => currentLeaderboard,
        getCurrentMode: () => currentMode,
        manualRefresh: () => window.refreshLeaderboard(),
        addTestScore: () => addScore(`TestPlayer${Math.floor(Math.random()*1000)}`, Math.floor(Math.random()*50000), currentMode),
        forceMode: (mode) => window.forceLeaderboardMode(mode),
        forceRefresh: () => window.forceRefreshLeaderboard(),
        debugModeDetection: () => {
            console.log('🔍 Current mode detection state:');
            console.log('  currentMode:', currentMode);
            console.log('  window.currentGameMode:', window.currentGameMode);
            console.log('  window.selectedGameMode:', window.selectedGameMode);
            console.log('  localStorage:', localStorage.getItem('ballDefender_selectedMode'));
            console.log('  currentLeaderboard.length:', currentLeaderboard.length);
            if (currentLeaderboard.length > 0) {
                console.log('  Top score:', currentLeaderboard[0]);
            }
        },
        // Test function to validate leaderboard system
        testLeaderboardSystem: async function() {
            console.log('🧪 Testing leaderboard system...');
            
            try {
                // Test 1: Mode detection
                console.log('🔬 Test 1: Mode detection');
                const detectedMode = detectGameMode();
                console.log(`✅ Detected mode: ${detectedMode}`);
                
                // Test 2: Authentication
                console.log('🔬 Test 2: Authentication');
                if (window.SecureHighScoreAuth) {
                    await window.SecureHighScoreAuth.authenticate();
                    console.log('✅ Authentication successful');
                } else {
                    throw new Error('SecureHighScoreAuth not available');
                }
                
                // Test 3: Test score submission
                console.log('🔬 Test 3: Test score submission');
                const testResult = await window.addToSupabaseLeaderboard(`TestIce${Date.now()}`, Math.floor(Math.random() * 10000), 'iceFrost');
                console.log('✅ Test score submission successful:', testResult);
                
                // Test 4: Check if we can read leaderboard
                console.log('🔬 Test 4: Reading leaderboard');
                const leaderboard = window.getLeaderboard('iceFrost');
                console.log(`✅ Got ${leaderboard.length} scores for iceFrost mode`);
                
                console.log('🎉 All leaderboard tests passed!');
                return true;
                
            } catch (error) {
                console.error('❌ Leaderboard test failed:', error);
                return false;
            }
        }
    };
    
    // Start the system
    initialize();
    
    console.log('🎮 Simple Supabase Leaderboard System Loaded (v1.2 - Cache busted)');
    console.log('💡 Minimal API calls - only loads on game start and mode changes');
    
})();
